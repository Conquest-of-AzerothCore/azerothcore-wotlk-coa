from dataclasses import dataclass
from pathlib import Path
import re
from typing import TYPE_CHECKING

from tooltip import CasterStats, Unreadable

if TYPE_CHECKING:
    from compare import TooltipSource, Verdict

QUESTIONS_FILE = 'questions.md'
READINGS_QUESTION = 'readings'
TEXT_QUESTION = 'text'
TOOLTIP_VALUE = 'tooltip_value'
DATA_ISSUE = 'data_issue'
SERVER_BEHAVIOUR = 'server_behaviour'
TITLE = '# Open conformance checks'
INTRO = ('Generated by `conformance.py compare`. Each entry is a check that the client data and our test server '
         'could not settle alone. Settle it from the reference Ascension combat logs '
         '(~/Projects/coa-log-history, May-Aug 2026): each entry names the log evidence that decides it. An entry '
         'with no log evidence stays open; record the query you ran as its reason.')
TOOLTIP_KINDS = (READINGS_QUESTION, TEXT_QUESTION, TOOLTIP_VALUE, DATA_ISSUE)
SERVER_KINDS = (SERVER_BEHAVIOUR,)
SECTIONS = (('Tooltips', TOOLTIP_KINDS,
             'The tooltip can be read in more than one way, or shows a number that the client data cannot give. '
             'Each entry quotes the client tooltip with its `$` tokens, the numbers those tokens show, each reading '
             'with what our test server measured, and what to look for in the reference logs.'),
            ('Findings', SERVER_KINDS,
             'Our test server does something the tooltip does not describe. Since production runs this same code, '
             'this is a finding, not a question: what the tooltip says, what the test server measured, and the log '
             'evidence (if any) that would confirm or rule out a defect.'))
COLOR_CODE = re.compile(r'\|c[0-9A-Fa-f]{8}|\|r', re.IGNORECASE)
SPELL_REFERENCE = re.compile(r'@s:(\d+):-?\d+@')
STATUS_TEXT = {'ok': 'matches the test server', 'alert': 'does not match the test server'}
ANY_STATS = (CasterStats(1, 0.0, 0.0, dict.fromkeys(range(1, 7), 0.0), dict.fromkeys(range(5), 0.0)),
             CasterStats(80, 1000.0, 1000.0, dict.fromkeys(range(1, 7), 1000.0), dict.fromkeys(range(5), 1000.0)))
DURATION_KIND = 'duration_ms'


@dataclass(frozen=True)
class Question:
    tooltip: str
    spells: tuple[tuple[int, str], ...]
    kind: str
    question: str
    readings: tuple[dict, ...]
    measured: float | None
    labels: tuple[str, ...]
    conditions: tuple[tuple[int, str], ...] = ()
    observations: tuple[tuple[int, str], ...] = ()


def cleaned(text) -> str:
    return COLOR_CODE.sub('', text if isinstance(text, str) else '').replace('\r\n', '\n').strip()


def asked(verdict: 'Verdict') -> dict | None:
    if verdict.status == 'ok':
        return None
    found = (verdict.detail or {}).get('question')
    if found:
        return found
    if verdict.status == 'ambiguous_tooltip':
        return {'kind': TEXT_QUESTION, 'question': verdict.explanation, 'readings': [], 'measured': verdict.measured}
    return None


def spell_of(verdict: 'Verdict') -> int:
    return verdict.rank_id or verdict.spell_id


def spell_name(tooltips: 'TooltipSource', spell_id: int) -> str:
    try:
        name = tooltips.spell_field(spell_id, 'SpellName[enUS]')
    except Unreadable:
        return str(spell_id)
    return name if isinstance(name, str) and name else str(spell_id)


def description(tooltips: 'TooltipSource', spell_id: int) -> str:
    try:
        return cleaned(tooltips.spell_field(spell_id, 'Description[enUS]'))
    except Unreadable:
        return ''


def added(items: list, item) -> None:
    if item not in items:
        items.append(item)


def questions(verdicts: list['Verdict'], tooltips: 'TooltipSource') -> list[Question]:
    grouped: dict[tuple, dict] = {}
    for verdict in verdicts:
        found = asked(verdict)
        if found is None:
            continue
        spell = spell_of(verdict)
        tooltip = description(tooltips, spell)
        key = (tooltip, found['kind']) if tooltip else (tooltip, found['kind'], spell)
        group = grouped.setdefault(key, {'spells': {}, 'questions': [], 'readings': [],
                                                              'measured': [], 'conditions': [], 'observations': [],
                                                              'labels': []})
        group['spells'].setdefault(spell, spell_name(tooltips, spell))
        added(group['questions'], found['question'])
        for reading in found.get('readings') or ():
            added(group['readings'], {**reading, 'spell': spell})
        added(group['measured'], found.get('measured'))
        for name in ('conditions', 'observations'):
            if found.get(name):
                added(group[name], (spell, found[name]))
        added(group['labels'], verdict.label)
    return [Question(tooltip, tuple(sorted(group['spells'].items())), kind, '\n'.join(group['questions']),
                     tuple(group['readings']), group['measured'][0] if len(group['measured']) == 1 else None,
                     tuple(group['labels']), tuple(group['conditions']), tuple(group['observations']))
            for (tooltip, kind, *_), group in grouped.items()]


def fixed_values(tooltips: 'TooltipSource', spell_id: int) -> list[str]:
    try:
        low, high = (tooltips.read(spell_id, stats).values for stats in ANY_STATS)
    except Unreadable:
        return []
    return [f'`{value.text}` {shown(value)}' for value, other in zip(low, high)
            if (value.text, value.value) == (other.text, other.value)]


def shown(value) -> str:
    if value.kind == DURATION_KIND:
        return f'{value.value / 1000:g} sec'
    return f'{value.value:g}'


def number(value: float | None, digits: str = 'g') -> str:
    return 'none' if value is None else format(value, digits)


def reading_line(reading: dict, prefix: str = '') -> str:
    head = f'- {prefix}{reading["name"]}'
    if reading.get('meaning'):
        head += f' ({reading["meaning"]})'
    if 'expects' in reading:
        text = f'expects {reading["expects"]}'
        if reading.get('measured_text'):
            text += f', test server {reading["measured_text"]}'
    elif 'trials' in reading and 'procs' in reading:
        if reading.get('rate') is None:
            text = f'{number(reading["procs"])} procs in {number(reading["trials"])} trials, no rate'
        else:
            text = (f'{number(reading["procs"])} procs in {number(reading["trials"])} trials, rate '
                    f'{reading["rate"]:.2%}, 99% interval {reading["low"]:.2%} to {reading["high"]:.2%}')
    else:
        unit = reading.get('unit', '')
        text = f'expects {number(reading.get("expected"), ".6g")}{unit}'
        if reading.get('delta') is not None:
            text += f' (change {reading["delta"]:+.6g})'
        if reading.get('trials') is not None:
            text += f' in {number(reading["trials"])} trials'
        if reading.get('measured') is not None:
            text += f', test server {number(reading["measured"], ".6g")}{unit}'
    status = reading.get('status')
    if status:
        text += f': {STATUS_TEXT.get(status, status)}'
    return f'{head}: {text}'


def spell_lines(title: str, items: tuple[tuple[int, str], ...], several: bool) -> list[str]:
    if not items:
        return []
    if not several:
        return ['', f'{title}: ' + ' '.join(text for _, text in items)]
    return ['', f'{title}:'] + [f'- {spell}: {text}' for spell, text in items]


def entry_lines(item: Question, tooltips: 'TooltipSource | None') -> list[str]:
    ids = ', '.join(str(spell) for spell, _ in item.spells)
    names = list(dict.fromkeys(name for _, name in item.spells))
    lines = [f'## {" / ".join(names)} ({ids})', '']
    quoted = SPELL_REFERENCE.sub(r' (followed by the tooltip of spell \1)', item.tooltip) or '(no tooltip text)'
    lines += [f'> {line}'.rstrip() for line in quoted.split('\n')]
    if tooltips is not None:
        values: dict[str, list[int]] = {}
        for spell, _ in item.spells:
            shown_values = ', '.join(fixed_values(tooltips, spell))
            if shown_values:
                values.setdefault(shown_values, []).append(spell)
        if values:
            lines += ['', 'Tooltip numbers from the client data, the same at any level and stats:']
            lines += [f'- {", ".join(map(str, spells))}: {shown_values}' for shown_values, spells in values.items()]
    several = len(item.spells) > 1
    lines += spell_lines('How we tested', item.conditions, several)
    if item.readings:
        lines += ['', 'Readings:'] + [reading_line(reading, f'{reading["spell"]} ' if several and 'spell' in reading
                                                   else '') for reading in item.readings]
    lines += spell_lines('Observations needed', item.observations, several)
    lines += ['']
    prefix = 'Finding' if item.kind in SERVER_KINDS else 'To settle'
    lines += [f'{prefix}: {question}' for question in item.question.split('\n')]
    lines += ['', f'Checks: {", ".join(f"`{label}`" for label in item.labels)}', '']
    return lines


def question_lines(items: list[Question], tooltips: 'TooltipSource | None' = None) -> list[str]:
    lines = [TITLE, '', INTRO, '']
    if not items:
        return lines + ['No question: every check was settled or is out of scope.', '']
    for title, kinds, intro in SECTIONS:
        section = sorted((item for item in items if (item.kind == SERVER_BEHAVIOUR) == (kinds == SERVER_KINDS)),
                         key=lambda item: kinds.index(item.kind) if item.kind in kinds else len(kinds))
        if section:
            lines += [f'# {title}', '', intro, '']
            for item in section:
                lines += entry_lines(item, tooltips)
    return lines


def write_questions(items: list[Question], out_dir: Path, tooltips: 'TooltipSource | None' = None) -> Path:
    path = Path(out_dir) / QUESTIONS_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(question_lines(items, tooltips)), encoding='utf-8')
    return path
