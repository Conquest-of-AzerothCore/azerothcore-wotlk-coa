CREATE TABLE IF NOT EXISTS `coa_pet_journal` (
  `account` INT UNSIGNED NOT NULL,
  `species` INT UNSIGNED NOT NULL,
  `level` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `xp` INT UNSIGNED NOT NULL DEFAULT 0,
  `ability1` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `ability2` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `ability3` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `quality` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `display` INT UNSIGNED NOT NULL DEFAULT 0,
  `health` INT UNSIGNED NOT NULL DEFAULT 0,
  `health_at` INT UNSIGNED NOT NULL DEFAULT 0,
  `revision` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`account`, `species`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS `coa_pet_team` (
  `account` INT UNSIGNED NOT NULL,
  `team` TINYINT UNSIGNED NOT NULL,
  `slot1` INT UNSIGNED NOT NULL DEFAULT 0,
  `slot2` INT UNSIGNED NOT NULL DEFAULT 0,
  `slot3` INT UNSIGNED NOT NULL DEFAULT 0,
  `revision` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`account`, `team`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS `coa_pet_account` (
  `account` INT UNSIGNED NOT NULL,
  `active_team` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `revision` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`account`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
