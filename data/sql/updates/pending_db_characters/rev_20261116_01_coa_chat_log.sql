CREATE TABLE IF NOT EXISTS `coa_chat_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `time` INT UNSIGNED NOT NULL,
  `account` INT UNSIGNED NOT NULL,
  `guid` INT UNSIGNED NOT NULL,
  `name` VARCHAR(25) NOT NULL,
  `type` TINYINT UNSIGNED NOT NULL,
  `lang` TINYINT UNSIGNED NOT NULL,
  `team` TINYINT UNSIGNED NOT NULL,
  `channel` VARCHAR(64) NOT NULL DEFAULT '',
  `target_guid` INT UNSIGNED NOT NULL DEFAULT 0,
  `target_account` INT UNSIGNED NOT NULL DEFAULT 0,
  `target_name` VARCHAR(25) NOT NULL DEFAULT '',
  `group_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `guild_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `map` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `zone` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `x` FLOAT NOT NULL DEFAULT 0,
  `y` FLOAT NOT NULL DEFAULT 0,
  `z` FLOAT NOT NULL DEFAULT 0,
  `emote` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `mail_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `subject` VARCHAR(255) NOT NULL DEFAULT '',
  `message` TEXT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_time` (`time`),
  KEY `idx_guid_time` (`guid`, `time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
