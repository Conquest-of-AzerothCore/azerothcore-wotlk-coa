CREATE TABLE IF NOT EXISTS `coa_economy_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `time` INT UNSIGNED NOT NULL,
  `account` INT UNSIGNED NOT NULL,
  `guid` INT UNSIGNED NOT NULL,
  `event` TINYINT UNSIGNED NOT NULL,
  `item_entry` INT UNSIGNED NOT NULL DEFAULT 0,
  `item_guid` INT UNSIGNED NOT NULL DEFAULT 0,
  `item_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `gold` BIGINT NOT NULL DEFAULT 0,
  `tokens` INT NOT NULL DEFAULT 0,
  `cost_item` INT UNSIGNED NOT NULL DEFAULT 0,
  `cost_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `other_account` INT UNSIGNED NOT NULL DEFAULT 0,
  `other_guid` INT UNSIGNED NOT NULL DEFAULT 0,
  `source` INT UNSIGNED NOT NULL DEFAULT 0,
  `map` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `zone` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_time` (`time`),
  KEY `idx_account_time` (`account`, `time`),
  KEY `idx_guid_time` (`guid`, `time`),
  KEY `idx_item_guid` (`item_guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
