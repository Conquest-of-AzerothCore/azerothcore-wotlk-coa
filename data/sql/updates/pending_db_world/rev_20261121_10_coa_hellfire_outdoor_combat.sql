CREATE TABLE IF NOT EXISTS `coa_zone_scaling` (
    `zone_id` INT UNSIGNED NOT NULL,
    `map_id` SMALLINT UNSIGNED NOT NULL,
    `zone_order` INT UNSIGNED NOT NULL,
    `health_step` FLOAT NOT NULL DEFAULT 0.2,
    `damage_step` FLOAT NOT NULL DEFAULT 0.2,
    `reward_level` SMALLINT UNSIGNED NOT NULL,
    `reward_min` SMALLINT UNSIGNED NOT NULL,
    `reward_max` SMALLINT UNSIGNED NOT NULL,
    `enabled` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (`zone_id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `coa_zone_creature_budget` (
    `zone_id` INT UNSIGNED NOT NULL,
    `entry` INT UNSIGNED NOT NULL,
    `level` TINYINT UNSIGNED NOT NULL,
    `health` INT UNSIGNED NOT NULL,
    `melee_multiplier` FLOAT NOT NULL DEFAULT 1,
    `spell_multiplier` FLOAT NOT NULL DEFAULT 1,
    `comment` VARCHAR(120) NOT NULL DEFAULT '',
    PRIMARY KEY (`zone_id`, `entry`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `coa_zone_item_budget` (
    `zone_id` INT UNSIGNED NOT NULL,
    `entry` INT UNSIGNED NOT NULL,
    `item_level` SMALLINT UNSIGNED NOT NULL,
    `pve_power` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `pvp_power` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`zone_id`, `entry`)
) ENGINE=InnoDB;

