-- Ascension's own Normal rank (same name, lower id, spell level 20) deals that rank's damage when the caster
-- is below level 50, worked out at the caster's level (direct hit, and damage per second of a periodic
-- effect); otherwise it deals the Heroic damage / 1.66 * 0.85 (high). Normal ranks keep their own values.
-- Generated by dungeon-recherche/normal_schaden.py.
