  `kit` INT UNSIGNED NOT NULL,
  `slot` TINYINT UNSIGNED NOT NULL,
  `unlock_level` TINYINT UNSIGNED NOT NULL,
  `ability` INT UNSIGNED NOT NULL,
  PRIMARY KEY (`kit`, `slot`, `unlock_level`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

