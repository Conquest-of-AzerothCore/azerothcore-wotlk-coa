-- Markers follow the client's QuestSuperTrack.dbc objective points (fields 2-81, twenty per objective) and turn-in
-- points (fields 82-101) with their SuperTrack.dbc radius:
--   radius up to 15 yd    a single pin on the client point;
--   larger radius         a square around the client circle;
--   turn-in               a pin at ObjectiveIndex -1.
-- ObjectiveIndex 0-3 are the RequiredNpcOrGo slots and 4 + slot the RequiredItemId slots, as in the stock data.
