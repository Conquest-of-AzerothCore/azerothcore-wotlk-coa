#!/usr/bin/env python3
"""Generate the Manastorm snapshot updates from the authored exports; never connects to a database."""

import argparse
import hashlib
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
REPAIR = HERE.parents[1] / "data/sql/db-world/updates/zz_manastorm_link_affix_eligibility.sql"
MODULE_SQL = HERE.parents[1] / "data/sql"
UPDATES = HERE.parents[1] / "data/sql/db-world/updates"
TELEPORT_SNAPSHOT = UPDATES / "zz_manastorm_snapshot_1_game_tele.sql"
WORLD_SNAPSHOT = UPDATES / "zz_manastorm_snapshot_2_world.sql"
TELEPORT_TUPLE = r"\(\s*(\d+)\s*,(?:\s*-?[\d.]+\s*,){5}\s*'((?:[^'\\]|\\.|'')*)'\s*\)"
BATCH_BYTES = 1 << 20


def upsert_batches(rows):
    batch, size = [], 0
    for table, values in rows:
        if batch and (table != batch[0][0] or size + len(values) > BATCH_BYTES):
            yield batch
            batch, size = [], 0
        batch.append((table, values))
        size += len(values) + 2
    if batch:
        yield batch


def world_sql(source):
    schemas = {}
    for match in re.finditer(r"CREATE TABLE `([^`]+)`\s*\((.*?)\n\)", source, re.S):
        table, body = match.groups()
        if not table.startswith("manastorm_"):
            raise ValueError(f"Unexpected table: {table}")
        columns = re.findall(r"^\s*`([^`]+)`\s", body, re.M)
        primary = re.search(r"PRIMARY KEY\s*\(([^)]+)\)", body)
        if not primary:
            raise ValueError(f"Missing primary key: {table}")
        keys = set(re.findall(r"`([^`]+)`", primary[1]))
        schemas[table] = (columns, keys, body)
    if len(schemas) != 25:
        raise ValueError(f"Expected 25 world tables, found {len(schemas)}")
    result = ["-- Generated by docs/manual-sql-postinstall/prepare_postinstall.py; do not edit.",
              "-- Authored world snapshot upserts; rows absent from the snapshot remain."]
    body = schemas["manastorm_unlock_message"][2]
    for column in ("source_field_1", "source_field_2", "source_field_3"):
        definition = re.search(r"^\s*(`" + column + r"`[^\n]+)", body, re.M)
        if not definition:
            raise ValueError(f"Missing source metadata: {column}")
        declaration = definition[1].rstrip().removesuffix(",")
        declaration = declaration.replace("\\", "\\\\").replace("'", "''")
        result.extend([
            "SET @ms_column_exists = (SELECT EXISTS (SELECT 1 FROM `information_schema`.`COLUMNS` "
            "WHERE `TABLE_SCHEMA` = DATABASE() AND `TABLE_NAME` = 'manastorm_unlock_message' "
            f"AND `COLUMN_NAME` = '{column}'));",
            "SET @ms_sql = IF(@ms_column_exists = 0, "
            f"'ALTER TABLE `manastorm_unlock_message` ADD COLUMN {declaration}', 'DO 0');",
            "PREPARE ms_statement FROM @ms_sql;",
            "EXECUTE ms_statement;",
            "DEALLOCATE PREPARE ms_statement;",
        ])
    rows = re.findall(r"^INSERT INTO `([^`]+)` VALUES (.*);$", source, re.M)
    if len(rows) != len(re.findall(r"^INSERT INTO ", source, re.M)):
        raise ValueError("Not every export INSERT was recognized")
    for batch in upsert_batches(rows):
        table = batch[0][0]
        columns, keys, _ = schemas[table]
        names = ", ".join(f"`{name}`" for name in columns)
        updates = ", ".join(f"`{name}` = VALUES(`{name}`)" for name in columns if name not in keys)
        values = ",\n".join(values for _, values in batch)
        result.append(f"INSERT INTO `{table}` ({names}) VALUES\n{values} ON DUPLICATE KEY UPDATE {updates};")
    result.append(REPAIR.read_text(encoding="utf-8").rstrip("\n"))
    return "\n".join(result) + "\n", len(rows)


def module_teleports():
    teleports = set()
    for path in sorted(MODULE_SQL.rglob("*.sql")):
        if path in (TELEPORT_SNAPSHOT, WORLD_SNAPSHOT):
            continue
        for statement in re.findall(r"INSERT\s+(?:IGNORE\s+)?INTO\s+`game_tele`[^;]*", path.read_text(encoding="utf-8-sig")):
            for teleport_id, name in re.findall(TELEPORT_TUPLE, statement):
                teleports.add((int(teleport_id), name))
    return teleports


def teleport_guard_sql(owners):
    ids = ", ".join(str(teleport_id) for teleport_id in sorted({teleport_id for teleport_id, _ in owners}))
    rows = ", ".join(f"({teleport_id}, '{name}')" for teleport_id, name in sorted(owners))
    return [
        "DROP TEMPORARY TABLE IF EXISTS `manastorm_tele_owner`, `manastorm_tele_conflict`, `manastorm_tele_guard`;",
        "CREATE TEMPORARY TABLE `manastorm_tele_owner` SELECT `id`, `name` FROM `game_tele` LIMIT 0;",
        f"INSERT INTO `manastorm_tele_owner` (`id`, `name`) VALUES {rows};",
        "CREATE TEMPORARY TABLE `manastorm_tele_conflict` SELECT `t`.`id`, `t`.`name` FROM `game_tele` `t` "
        "LEFT JOIN `manastorm_tele_owner` `o` ON `o`.`id` = `t`.`id` AND `o`.`name` = `t`.`name` "
        f"WHERE `t`.`id` IN ({ids}) AND `o`.`id` IS NULL;",
        "SELECT `id` AS `foreign_teleport_id`, `name` AS `foreign_teleport_name` FROM `manastorm_tele_conflict`;",
        "CREATE TEMPORARY TABLE `manastorm_tele_guard` (`foreign_teleport_found` INT NOT NULL, "
        "CONSTRAINT `manastorm_teleport_ids_free` CHECK (`foreign_teleport_found` = 0));",
        "INSERT INTO `manastorm_tele_guard` SELECT EXISTS (SELECT 1 FROM `manastorm_tele_conflict`);",
    ]


def teleport_sql(source):
    result = ["-- Generated by docs/manual-sql-postinstall/prepare_postinstall.py; do not edit.",
              "-- Rows already holding an authored id are overwritten only when they carry the authored name",
              "-- or the name the module SQL gave that id. Any other teleport on those ids is listed and",
              "-- violates `manastorm_teleport_ids_free` before any change, which stops the update."]
    upserts = []
    owners = set()
    pattern = r"^INSERT INTO `acore_world`\.`game_tele` (\([^\n]+?\)) VALUES (.*);$"
    for match in re.finditer(pattern, source, re.M):
        columns, values = match.groups()
        authored = re.fullmatch(TELEPORT_TUPLE, values)
        if not authored:
            raise ValueError(f"Unrecognized teleport tuple: {values}")
        owners.add((int(authored[1]), authored[2]))
        names = re.findall(r"`([^`]+)`", columns)
        updates = ", ".join(f"`{name}` = VALUES(`{name}`)" for name in names if name != "id")
        upserts.append(f"INSERT INTO `game_tele` {columns} VALUES {values} ON DUPLICATE KEY UPDATE {updates};")
    count = len(upserts)
    if count != 163 or count != len(re.findall(r"^INSERT INTO ", source, re.M)) or len(owners) != count:
        raise ValueError("Expected all 163 authored teleports")
    authored_ids = {teleport_id for teleport_id, _ in owners}
    owners |= {teleport for teleport in module_teleports() if teleport[0] in authored_ids}
    result += teleport_guard_sql(owners) + upserts
    result.append("DROP TEMPORARY TABLE `manastorm_tele_owner`, `manastorm_tele_conflict`, `manastorm_tele_guard`;")
    return "\n".join(result) + "\n", count


def snapshots():
    sources = [HERE / "Gametele.sql", HERE / "ManastormWorldDBExport-RUNTHIS.sql"]
    hashes = {path: hashlib.sha256(path.read_bytes()).hexdigest() for path in sources}
    teleports, tele_count = teleport_sql(sources[0].read_text(encoding="utf-8-sig"))
    world, world_count = world_sql(sources[1].read_text(encoding="utf-8-sig"))
    if any(hashlib.sha256(path.read_bytes()).hexdigest() != digest for path, digest in hashes.items()):
        raise RuntimeError("Source export changed during preparation")
    return {TELEPORT_SNAPSHOT: teleports, WORLD_SNAPSHOT: world}, tele_count, world_count


def stale_snapshots(files):
    return [path for path, text in files.items()
            if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8")]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed snapshot updates are stale")
    args = parser.parse_args()
    files, tele_count, world_count = snapshots()
    stale = stale_snapshots(files)
    if args.check:
        for path in stale:
            print(f"Stale snapshot update: {path.name}")
        return 1 if stale else 0
    for path in stale:
        path.write_text(files[path], encoding="utf-8", newline="\n")
    print(f"{len(stale)} of {len(files)} snapshot updates written: {tele_count} teleports, {world_count} world rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
